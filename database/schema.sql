CREATE TABLE IF NOT EXISTS prescriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
  pharmacy_id BIGINT NOT NULL REFERENCES pharmacies(id) ON DELETE CASCADE,
  storage_key TEXT UNIQUE,
  original_filename TEXT NOT NULL,
  mime_type TEXT NOT NULL CHECK (mime_type IN ('application/pdf', 'image/jpeg', 'image/png')),
  file_size INTEGER NOT NULL CHECK (file_size > 0 AND file_size <= 5242880),
  file_sha256 TEXT,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected', 'correction_required')),
  prescription_date DATE,
  valid_until DATE,
  review_reason TEXT,
  reviewed_by_user_account_id BIGINT REFERENCES user_accounts(id) ON DELETE SET NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at TIMESTAMPTZ,
  retention_until DATE NOT NULL DEFAULT (CURRENT_DATE + 30),
  document_deleted_at TIMESTAMPTZ,
  CHECK ((storage_key IS NULL) = (document_deleted_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS prescriptions_customer_submitted_idx
  ON prescriptions(customer_account_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS prescriptions_pharmacy_status_idx
  ON prescriptions(pharmacy_id, status, submitted_at);
CREATE INDEX IF NOT EXISTS prescriptions_retention_idx
  ON prescriptions(retention_until) WHERE storage_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS prescription_medicines (
  prescription_id BIGINT NOT NULL REFERENCES prescriptions(id) ON DELETE CASCADE,
  medicine_id BIGINT NOT NULL REFERENCES medicines(id) ON DELETE RESTRICT,
  requested_quantity INTEGER NOT NULL CHECK (requested_quantity > 0),
  approved_quantity INTEGER CHECK (approved_quantity IS NULL OR approved_quantity > 0),
  reserved_quantity INTEGER NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0),
  medicine_matches BOOLEAN,
  PRIMARY KEY (prescription_id, medicine_id),
  CHECK (approved_quantity IS NULL OR reserved_quantity <= approved_quantity)
);

