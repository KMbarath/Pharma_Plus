CREATE OR REPLACE FUNCTION reject_sales_order_item_snapshot_changes()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF ROW(
    OLD.order_id, OLD.medicine_name, OLD.quantity,
    OLD.unit_price, OLD.line_total, OLD.medicine_snapshot
  ) IS DISTINCT FROM ROW(
    NEW.order_id, NEW.medicine_name, NEW.quantity,
    NEW.unit_price, NEW.line_total, NEW.medicine_snapshot
  ) THEN
    RAISE EXCEPTION 'Order item snapshots are immutable'
      USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END;
$$;

