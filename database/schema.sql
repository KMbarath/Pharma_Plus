CREATE TABLE IF NOT EXISTS medicines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pharmacy_id BIGINT REFERENCES pharmacies(id) ON DELETE CASCADE,
  sku TEXT,
  name TEXT NOT NULL,
  brand_name TEXT,
  generic_name TEXT,
  strength TEXT,
  dosage_form TEXT,
  pack_quantity INTEGER CHECK (pack_quantity IS NULL OR pack_quantity > 0),
  pack_unit TEXT,
  category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
  supplier_id BIGINT REFERENCES suppliers(id) ON DELETE SET NULL,
  pack TEXT NOT NULL DEFAULT '',
  manufacturer TEXT,
  batch_number TEXT,
  expiry_date DATE,
  price NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  mrp NUMERIC(12, 2) CHECK (mrp IS NULL OR mrp >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  reorder_level INTEGER NOT NULL DEFAULT 10 CHECK (reorder_level >= 0),
  unit TEXT NOT NULL DEFAULT 'units',
  hsn_code TEXT,
  gst_rate NUMERIC(5, 2) NOT NULL DEFAULT 0 CHECK (gst_rate >= 0 AND gst_rate <= 100),
  prescription_required BOOLEAN NOT NULL DEFAULT false,
  description TEXT,
  image_url TEXT,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

