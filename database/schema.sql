CREATE INDEX IF NOT EXISTS inventory_batches_available_idx
  ON inventory_batches(medicine_id, expiry_date, received_at)
  WHERE quantity_remaining > 0;
INSERT INTO inventory_batches
  (medicine_id, batch_number, quantity_received, quantity_remaining, expiry_date)
SELECT m.id, 'LEGACY-' || m.id,
       m.stock - COALESCE(batches.quantity_remaining, 0),
       m.stock - COALESCE(batches.quantity_remaining, 0),
       m.expiry_date
FROM medicines m
LEFT JOIN LATERAL (
  SELECT SUM(b.quantity_remaining) AS quantity_remaining
  FROM inventory_batches b
  WHERE b.medicine_id = m.id
) batches ON true
WHERE m.stock > COALESCE(batches.quantity_remaining, 0)
AND NOT EXISTS (
  SELECT 1 FROM inventory_batches b
  WHERE b.medicine_id = m.id AND b.batch_number = 'LEGACY-' || m.id
);

